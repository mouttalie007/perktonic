import type { CategoryKey } from "./site";

/**
 * Registry of PerkTonic's online tools: the single source for the homepage
 * "Popular Tools" row, the /tools hub and each /tools/<slug> page.
 *
 * A tool is `soon` until it is delivered. To ship one: drop its folder in
 * `src/tools/<slug>/`, map its component in `src/tools/registry.tsx` and flip
 * `status` to "live". Only live tools are listed in the sitemap.
 */
export type ToolStatus = "live" | "soon";

export interface ToolDef {
  slug: string;
  name: string;
  description: string;
  categorySlug: CategoryKey;
  /** ToolIcon key. */
  iconKey: string;
  status: ToolStatus;
  /** Shown first on the homepage / hub. */
  popular?: boolean;
  /** The tool sends what the visitor types (a URL) to our server; the page says so instead of "runs in your browser". */
  serverSide?: boolean;
  /** The tool sends the visitor's text to our server and to the AI provider, only when the visitor presses the button. */
  ai?: boolean;
  /** Replaces the trust badge text when neither "runs in your browser" nor "only the URL is sent" is true (tools that keep data on our server). */
  badge?: string;
}

